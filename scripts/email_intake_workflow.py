"""n8n workflow 2: "Email intake".

Every minute, finds two kinds of email and sends each one to the agent
(workflow 1) as a lead message:
  - new leads: messages carrying the lead-demo label
  - replies: new messages in the Gmail thread of a recent email lead. These
    don't carry the label (Gmail doesn't add it to replies), which is why the
    agent remembers each lead's thread.

Same rules as the invoice project's email intake, for the same reasons:
  - A schedule and a search, never n8n's Gmail Trigger. The trigger only sees
    messages that arrived since its last poll, and a label is always applied
    after arrival, so labelled messages were silently skipped.
  - The label is the queue: it comes off once the agent has the message, and
    stays on after a failure so the next run retries it.
  - The label is lead-demo, a name no existing filter would ever apply.

Messages the agent has already seen are skipped by their Gmail id (stored as
the message's external_id), and anything sent from the intake address itself
is ignored, so the agent can never answer its own emails.

Built and deployed by scripts/build_n8n_workflows.py.
"""

from __future__ import annotations

import json

from build_n8n_workflows import (
    IS_TRUE, PREFIX, ROOT, branch, code, gmail_request, if_node, link, node, rpc, slack_escaped,
    slack_post, supabase_request,
    AGENT_WEBHOOK_PATH,
)

OUTPUT = ROOT / "n8n" / "workflows" / "lead-email-intake.json"
WORKFLOW_NAME = f"{PREFIX} 2. Email intake"

LABEL_NAME = "lead-demo"
MAX_NEW_PER_RUN = 10
GMAIL_API = "https://gmail.googleapis.com/gmail/v1/users/me"
# Replies are looked for among recent inbox mail, in threads of leads from the last 30 days.
REPLY_SEARCH = f"in:inbox newer_than:2d -label:{LABEL_NAME}"


def config_code(env: dict) -> str:
    settings = {
        "supabase_url": env["SUPABASE_URL"].rstrip("/"),
        "agent_url": env["N8N_BASE_URL"].rstrip("/") + "/webhook/" + AGENT_WEBHOOK_PATH,
        "webhook_secret": env["N8N_WEBHOOK_SECRET"],
        "alerts_channel": env["SLACK_ALERTS_CHANNEL_ID"],
        "intake_address": env["GMAIL_INTAKE_ADDRESS"].lower(),
        "label_name": LABEL_NAME,
    }
    return ("// Generated by scripts/build_n8n_workflows.py.\n"
            f"return [{{ json: {json.dumps(settings, indent=2)} }}];")


CHECK_MAILBOX_CODE = """// Safety check: only ever read the mailbox this demo is meant to use.
const config = $('Config').first().json;
const address = String($input.first().json.emailAddress || '').toLowerCase();
if (address !== config.intake_address) {
  throw new Error(`The Gmail credential is signed in to ${address || 'an unknown account'}, not ${config.intake_address}.`);
}
return [{ json: { ok: true } }];"""


FIND_LABEL_CODE = """// Gmail needs a label id, not a name, to search by it and take it off.
const wanted = $('Config').first().json.label_name.toLowerCase();
const match = ($input.first().json.labels || []).find(l => String(l.name).toLowerCase() === wanted);
if (!match) throw new Error(`No Gmail label named "${$('Config').first().json.label_name}". Create it first.`);
return [{ json: { label_id: match.id } }];"""


CANDIDATES_CODE = """// New leads (labelled) plus replies (recent mail in a known lead thread).
const labelled = $('List labelled').first().json.messages || [];
const recent = $('List recent').first().json.messages || [];
const threads = new Set(($('Get lead threads').all() || []).map(i => i.json.email_thread_id).filter(Boolean));

const seen = new Set();
const out = [];
for (const m of labelled) {
  if (!seen.has(m.id)) { seen.add(m.id); out.push({ json: { id: m.id, labelled: true } }); }
}
for (const m of recent) {
  if (threads.has(m.threadId) && !seen.has(m.id)) { seen.add(m.id); out.push({ json: { id: m.id, labelled: false } }); }
}
return out;  // nothing to do means no items, and the run stops here"""


NEW_ONLY_CODE = """// Sort by what leads.email_states says about messages already stored:
//   done   only needs its label taken off
//   busy   the agent is on it now, so leave it alone this time
//   retry  the agent failed on it and it's time to try again
// Anything not listed is new.
const state = new Map(($input.all() || []).filter(i => i.json.external_id).map(i => [i.json.external_id, i.json.state]));
return $('Candidates').all()
  .filter(i => state.get(i.json.id) !== 'busy')
  .map(i => ({ json: { ...i.json, already_in: state.get(i.json.id) === 'done' } }));"""


PARSE_EMAIL_CODE = r"""// Turn a Gmail message into a lead message: sender, subject, plain-text body
// with the quoted history cut off.
const config = $('Config').first().json;
const msg = $json;
const headers = {};
for (const h of msg.payload?.headers || []) headers[String(h.name).toLowerCase()] = h.value;

const fromRaw = headers.from || '';
const m = fromRaw.match(/^\s*"?([^"<]*?)"?\s*<([^>]+)>\s*$/);
const email = (m ? m[2] : fromRaw).trim().toLowerCase();
const name = (m ? m[1] : '').trim() || null;

const decode = data => Buffer.from(String(data).replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8');
const find = (part, type) => {
  if (!part) return null;
  if (part.mimeType === type && part.body?.data) return decode(part.body.data);
  for (const p of part.parts || []) { const found = find(p, type); if (found) return found; }
  return null;
};
let text = find(msg.payload, 'text/plain');
if (!text) {
  const html = find(msg.payload, 'text/html') || '';
  text = html.replace(/<br\s*\/?>/gi, '\n').replace(/<\/p>/gi, '\n').replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ');
}
// Cut the quoted earlier messages so the agent only reads what's new. Gmail
// often wraps the "On <date>, <name> <address> wrote:" line in two.
text = text.split(/\r?\n[^\n]*\bOn [\s\S]{0,300}?wrote:/)[0]
           .split(/\r?\n-{2,} ?Original Message/i)[0]
           .split(/\r?\n>/)[0]
           .trim()
           .slice(0, 4000);

const own = email === config.intake_address;
const automated = /mailer-daemon|no-?reply|postmaster/i.test(email);

return {
  json: {
    id: msg.id,
    labelled: $('New only').item.json.labelled,
    skip: own || automated || !text,
    skip_reason: own ? 'sent by the intake address' : automated ? 'automated sender' : !text ? 'empty' : null,
    payload: {
      source: 'email',
      message: text,
      name,
      email,
      subject: headers.subject || null,
      external_id: msg.id,
      thread_id: msg.threadId,
      message_id_header: headers['message-id'] || null,
    },
  },
};"""


SUMMARIZE_CODE = """// What happened to this message. 200 means the agent has dealt with it, unless
// another run got to it first: then that run decides, and there's nothing to report.
const src = $('Parse email').item.json;
const duplicate = $json.body?.duplicate === true;
const ok = $json.statusCode === 200 && !duplicate;
return { json: { id: src.id, labelled: src.labelled, from: src.payload.email, status: $json.statusCode ?? 'no answer',
                 ok, failed: !ok && !duplicate, gave_up: ($json.body?.attempts ?? 0) >= 3, final_action: $json.body?.final_action ?? null } };"""


def build_email_intake_workflow(env: dict) -> dict:
    y, row2 = 300, 520
    x = lambda col: col * 220  # noqa: E731
    label_id = "$('Find label').first().json.label_id"

    nodes = [
        node("Every minute", "n8n-nodes-base.scheduleTrigger", 1.2, (x(0), y), {
            "rule": {"interval": [{"field": "minutes", "minutesInterval": 1}]},
        }),
        code("Config", (x(1), y), config_code(env)),
        gmail_request("Get mailbox", (x(2), y), "GET", f"{GMAIL_API}/profile"),
        code("Check mailbox", (x(3), y), CHECK_MAILBOX_CODE),
        gmail_request("Get labels", (x(4), y), "GET", f"{GMAIL_API}/labels"),
        code("Find label", (x(5), y), FIND_LABEL_CODE),
        gmail_request("List labelled", (x(6), y), "GET",
                      f"={GMAIL_API}/messages?maxResults={MAX_NEW_PER_RUN}&labelIds={{{{ {label_id} }}}}"),
        supabase_request(
            "Get lead threads", (x(7), y), "GET",
            "/rest/v1/leads?select=email_thread_id&email_thread_id=not.is.null"
            "&updated_at=gte.{{ new Date(Date.now() - 30 * 864e5).toISOString() }}",
            alwaysOutputData=True, executeOnce=True,
        ),
        gmail_request("List recent", (x(8), y), "GET",
                      f"={GMAIL_API}/messages?maxResults=50&q={{{{ encodeURIComponent({json.dumps(REPLY_SEARCH)}) }}}}",
                      executeOnce=True),
        code("Candidates", (x(9), y), CANDIDATES_CODE),
        rpc("Already in?", (x(10), y), "email_states",
            "={{ JSON.stringify({ p_ids: $('Candidates').all().map(i => i.json.id) }) }}",
            alwaysOutputData=True, executeOnce=True),
        code("New only", (x(11), y), NEW_ONLY_CODE),
        if_node("Already in agent?", (x(12), y), "={{ $json.already_in }}", IS_TRUE),
        gmail_request("Get message", (x(13), y), "GET", f"={GMAIL_API}/messages/{{{{ $json.id }}}}?format=full"),
        code("Parse email", (x(14), y), PARSE_EMAIL_CODE, per_item=True),
        if_node("Skip?", (x(15), y), "={{ $json.skip }}", IS_TRUE),
        node("Send to agent", "n8n-nodes-base.httpRequest", 4.2, (x(16), y), {
            "method": "POST",
            "url": "={{ $('Config').first().json.agent_url }}",
            "sendHeaders": True,
            "headerParameters": {"parameters": [
                {"name": "x-webhook-secret", "value": "={{ $('Config').first().json.webhook_secret }}"},
            ]},
            "sendBody": True,
            "specifyBody": "json",
            "jsonBody": "={{ JSON.stringify($json.payload) }}",
            "options": {"timeout": 120000, "response": {"response": {"fullResponse": True, "neverError": True}}},
        # No retryOnFail: it would run the agent (two paid AI calls) more than once.
        # leads.email_states decides when a failed message is tried again.
        }, onError="continueRegularOutput"),
        code("Summarize", (x(17), y), SUMMARIZE_CODE, per_item=True),
        if_node("Agent has it?", (x(18), y), "={{ $json.ok }}", IS_TRUE),
        if_node("Labelled?", (x(19), y), "={{ $json.labelled }}", IS_TRUE),
        gmail_request("Take label off", (x(20), y), "POST", f"={GMAIL_API}/messages/{{{{ $json.id }}}}/modify",
                      body="={{ JSON.stringify({ removeLabelIds: [" + label_id + "] }) }}",
                      onError="continueRegularOutput"),
        if_node("Failed?", (x(19), row2), "={{ $json.failed }}", IS_TRUE),
        slack_post("Alert team", (x(20), row2),
                   "={{ JSON.stringify({ channel: $('Config').first().json.alerts_channel, "
                   "text: ':warning: The agent could not answer an email from ' + "
                   + slack_escaped("$json.from || 'unknown sender'") + " + ' (status ' + $json.status + '). ' + "
                   "($json.gave_up ? 'That was the third try, so please answer this one yourself.' "
                   ": 'It will be tried again in a few minutes.') }) }}"),
    ]

    connections = {
        "Every minute": link("Config"),
        "Config": link("Get mailbox"),
        "Get mailbox": link("Check mailbox"),
        "Check mailbox": link("Get labels"),
        "Get labels": link("Find label"),
        "Find label": link("List labelled"),
        "List labelled": link("Get lead threads"),
        "Get lead threads": link("List recent"),
        "List recent": link("Candidates"),
        "Candidates": link("Already in?"),
        "Already in?": link("New only"),
        "New only": link("Already in agent?"),
        "Already in agent?": branch(["Labelled?"], ["Get message"]),
        "Get message": link("Parse email"),
        "Parse email": link("Skip?"),
        "Skip?": branch(["Labelled?"], ["Send to agent"]),
        "Send to agent": link("Summarize"),
        "Summarize": link("Agent has it?"),
        "Agent has it?": branch(["Labelled?"], ["Failed?"]),
        "Failed?": branch(["Alert team"], []),
        "Labelled?": branch(["Take label off"], []),
    }
    return {
        "name": WORKFLOW_NAME,
        "nodes": nodes,
        "connections": connections,
        # Runs every minute and usually finds nothing, so only failures are kept.
        "settings": {"executionOrder": "v1", "saveDataSuccessExecution": "none", "saveDataErrorExecution": "all"},
    }
