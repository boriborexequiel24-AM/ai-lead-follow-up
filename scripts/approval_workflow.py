"""n8n workflow 3: "Price approval".

Slack calls this workflow when the owner clicks Approve or Reject on a price
in #lead-approvals. It:
  1. Checks the request really came from Slack (signature + timestamp).
  2. Records the decision in the database (leads.resolve_approval), only if
     the price is still pending, so a double click is harmless.
  3. Approved: the reply appears in the web thread right away, and email
     leads get it by email (allow-listed addresses only). Rejected: nothing
     is sent and the lead is handed to the owner.
  4. Replaces the buttons in Slack with the outcome.

Built and deployed by scripts/build_n8n_workflows.py.
"""

from __future__ import annotations

import json

from build_n8n_workflows import (
    BUILD_EMAIL_CODE, COMPANY_NAME, EMAIL_FOOTER, IS_TRUE, PREFIX, ROOT, SLACK_BLOCKS_JS,
    branch, code, gmail_request, if_node, link, node, node_id, rpc, slack_post, switch_on_kind,
)

OUTPUT = ROOT / "n8n" / "workflows" / "lead-price-approval.json"
WORKFLOW_NAME = f"{PREFIX} 3. Price approval"
WEBHOOK_PATH = "lead-slack-actions"


def config_code(env: dict) -> str:
    settings = {
        "supabase_url": env["SUPABASE_URL"].rstrip("/"),
        "signing_secret": env["SLACK_SIGNING_SECRET"],
        "alerts_channel": env["SLACK_ALERTS_CHANNEL_ID"],
        "intake_address": env["GMAIL_INTAKE_ADDRESS"].lower(),
        "allowlist": [a.strip().lower() for a in env.get("OUTBOUND_EMAIL_ALLOWLIST", "").split(",") if a.strip()],
        "company_name": COMPANY_NAME,
        "email_footer": EMAIL_FOOTER,
    }
    return ("// Settings for this workflow. Generated by scripts/build_n8n_workflows.py.\n"
            f"return [{{ json: {json.dumps(settings, indent=2)}, binary: $input.first().binary }}];")


READ_REQUEST_CODE = """// Slack signs every request it sends. Rebuild the signed text so the next step can check it.
const request = $('Slack action').first();
const headers = request.json.headers || {};
const timestamp = headers['x-slack-request-timestamp'] || '';
const signature = headers['x-slack-signature'] || '';

const binaryKey = Object.keys($input.first().binary || {})[0];
const raw = binaryKey ? (await this.helpers.getBinaryDataBuffer(0, binaryKey)).toString('utf8') : '';

const payloadText = request.json.body?.payload;
const ageSeconds = Math.abs(Date.now() / 1000 - Number(timestamp));

return [{
  json: {
    base_string: `v0:${timestamp}:${raw}`,
    signature,
    has_raw_body: raw.length > 0,
    fresh: Number.isFinite(ageSeconds) && ageSeconds < 300,  // reject replays older than 5 minutes
    payload: payloadText ? JSON.parse(payloadText) : null,
  },
}];"""


READ_DECISION_CODE = """// Which button was clicked, on which price, by whom.
const payload = $('Read Slack request').first().json.payload;
const action = payload?.actions?.[0];
if (!action || !['approve_price', 'reject_price'].includes(action.action_id)) return [];
const id = Number(action.value);
if (!Number.isInteger(id) || id <= 0) return [];

return [{
  json: {
    approved: action.action_id === 'approve_price',
    approval_id: id,
    user: payload.user?.name || payload.user?.username || payload.user?.id || 'someone',
    channel: payload.channel?.id || payload.container?.channel_id || null,
    message_ts: payload.message?.ts || payload.container?.message_ts || null,
  },
}];"""


PLAN_EFFECTS_CODE = SLACK_BLOCKS_JS + r"""
// The email to send (approved email leads) and the Slack message update.
const config = $('Config').first().json;
const d = $('Read decision').first().json;
const r = $input.first().json;
const out = [];

let outcome;
if (r.status === 'withdrawn') {
  outcome = r.unsubscribed
    ? `:no_entry: Approved by ${d.user}, but the lead has unsubscribed, so nothing was sent.`
    : ':leftwards_arrow_with_hook: Withdrawn: the conversation moved on before this was decided. Nothing was sent.';
} else if (!r.changed) {
  outcome = `:information_source: Already ${r.status}${r.decided_by ? ' by ' + r.decided_by : ''}. No change made.`;
} else if (!d.approved) {
  outcome = `:x: Rejected by ${d.user}. Nothing was sent; the lead is yours to follow up.`;
} else if (r.channel === 'email') {
  const to = String(r.lead.email || '').toLowerCase();
  if (config.allowlist.includes(to)) {
    out.push({ json: { kind: 'email', to, subject: r.subject, reply: r.reply, thread_id: r.thread_id, in_reply_to: null } });
    outcome = `:white_check_mark: Approved by ${d.user} and emailed to the customer.`;
  } else {
    outcome = `:white_check_mark: Approved by ${d.user}, but not emailed: ${to} isn't on OUTBOUND_EMAIL_ALLOWLIST.`;
  }
} else {
  outcome = `:white_check_mark: Approved by ${d.user} and sent to the customer's web thread.`;
}

const p = { approval_id: d.approval_id, who: whoLine(r.lead), summary: r.lead.summary, reply: r.reply };
out.push({ json: { kind: 'slack', body: { channel: d.channel, ts: d.message_ts, text: outcome,
                                          blocks: priceApprovalBlocks(p, outcome) } } });
return out;"""


def build_approval_workflow(env: dict) -> dict:
    y, row2 = 300, 520
    x = lambda col: col * 230  # noqa: E731

    nodes = [
        node("Slack action", "n8n-nodes-base.webhook", 2, (x(0), y), {
            "httpMethod": "POST",
            "path": WEBHOOK_PATH,
            "responseMode": "onReceived",  # Slack needs an answer within 3 seconds
            "options": {"rawBody": True},  # needed to check Slack's signature
        }, webhookId=node_id("slack-webhook")),
        code("Config", (x(1), y), config_code(env)),
        code("Read Slack request", (x(2), y), READ_REQUEST_CODE),
        node("Sign request", "n8n-nodes-base.crypto", 1, (x(3), y), {
            "action": "hmac",
            "type": "SHA256",
            "value": "={{ $json.base_string }}",
            "dataPropertyName": "expected_signature",
            "secret": "={{ $('Config').first().json.signing_secret }}",
            "encoding": "hex",
        }),
        if_node("Genuine Slack request?", (x(4), y),
                "={{ $json.fresh && $json.has_raw_body && ('v0=' + $json.expected_signature) === $json.signature }}",
                IS_TRUE),
        code("Read decision", (x(5), y), READ_DECISION_CODE),
        rpc("Resolve approval", (x(6), y), "resolve_approval",
            "={{ JSON.stringify({ p_approval_id: $json.approval_id, p_approved: $json.approved, p_decided_by: $json.user }) }}",
            onError="continueErrorOutput"),
        code("Plan side effects", (x(7), y), PLAN_EFFECTS_CODE),
        switch_on_kind("Email or Slack?", (x(8), y), ["email", "slack"]),
        code("Build email", (x(9), y), BUILD_EMAIL_CODE, per_item=True),
        gmail_request("Send email", (x(10), y), "POST",
                      "https://gmail.googleapis.com/gmail/v1/users/me/messages/send",
                      body="={{ JSON.stringify($json.send) }}", onError="continueErrorOutput"),
        slack_post("Alert email failed", (x(11), y + 160),
                   "={{ JSON.stringify({ channel: $('Config').first().json.alerts_channel, "
                   "text: ':warning: A price was approved but the email could not be sent: ' + "
                   "String($json.error?.message ?? $json.error ?? 'unknown error').slice(0, 300) }) }}"),
        node("Update Slack message", "n8n-nodes-base.httpRequest", 4.2, (x(9), row2), {
            "method": "POST",
            "url": "https://slack.com/api/chat.update",
            "authentication": "predefinedCredentialType",
            "nodeCredentialType": "slackApi",
            "sendBody": True,
            "specifyBody": "json",
            "jsonBody": "={{ JSON.stringify($json.body) }}",
            "options": {},
        }, onError="continueRegularOutput"),
        slack_post("Alert approval failed", (x(7), row2),
                   "={{ JSON.stringify({ channel: $('Config').first().json.alerts_channel, "
                   "text: ':warning: An approval click could not be recorded: ' + "
                   "String($json.error?.message ?? $json.error ?? 'unknown error').slice(0, 300) }) }}"),
    ]

    connections = {
        "Slack action": link("Config"),
        "Config": link("Read Slack request"),
        "Read Slack request": link("Sign request"),
        "Sign request": link("Genuine Slack request?"),
        "Genuine Slack request?": branch(["Read decision"], []),
        "Read decision": link("Resolve approval"),
        "Resolve approval": branch(["Plan side effects"], ["Alert approval failed"]),
        "Plan side effects": link("Email or Slack?"),
        "Email or Slack?": branch(["Build email"], ["Update Slack message"]),
        "Build email": link("Send email"),
        "Send email": branch([], ["Alert email failed"]),
    }
    return {"name": WORKFLOW_NAME, "nodes": nodes, "connections": connections,
            "settings": {"executionOrder": "v1"}}
