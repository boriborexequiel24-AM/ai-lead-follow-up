"""n8n workflow 5: "Cleanup".

Every hour, runs leads.cleanup(): deletes visitor leads older than the
retention in leads.settings (24 hours by default; their messages, decisions
and approvals go with them and their booked slots open up again), then makes
sure the coming week has visit slots.

Built and deployed by scripts/build_n8n_workflows.py.
"""

from __future__ import annotations

import json

from build_n8n_workflows import PREFIX, ROOT, code, link, node, rpc

OUTPUT = ROOT / "n8n" / "workflows" / "lead-cleanup.json"
WORKFLOW_NAME = f"{PREFIX} 5. Cleanup"


def build_cleanup_workflow(env: dict) -> dict:
    settings = {"supabase_url": env["SUPABASE_URL"].rstrip("/")}
    nodes = [
        node("Every hour", "n8n-nodes-base.scheduleTrigger", 1.2, (0, 300), {
            "rule": {"interval": [{"field": "hours", "hoursInterval": 1}]},
        }),
        code("Config", (220, 300), "// Generated by scripts/build_n8n_workflows.py.\n"
                                    f"return [{{ json: {json.dumps(settings)} }}];"),
        rpc("Run cleanup", (440, 300), "cleanup", "={{ JSON.stringify({}) }}"),
    ]
    connections = {"Every hour": link("Config"), "Config": link("Run cleanup")}
    return {"name": WORKFLOW_NAME, "nodes": nodes, "connections": connections,
            "settings": {"executionOrder": "v1"}}
