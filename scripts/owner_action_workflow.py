"""n8n workflow 6: "Demo owner action".

On the demo site, a visitor who asked for a price gets to play the owner: their
thread shows Approve / Reject, which calls this workflow (through the site's
server, with the webhook secret). It does what the Slack button does in
workflow 3:
  1. Records the decision with leads.visitor_resolve_approval, which only
     works for the price waiting in that visitor's own thread.
  2. Answers the site, which then shows the approved reply (or the hand-off).
  3. Replaces the buttons on the Slack message with the outcome, so Slack and
     the site never disagree.
Visitor leads come from the web form and are never emailed, so there is no
email step.

Built and deployed by scripts/build_n8n_workflows.py.
"""

from __future__ import annotations

import json

from build_n8n_workflows import (
    IS_TRUE, PREFIX, ROOT, SLACK_BLOCKS_JS, code, if_node, link, branch, node, node_id, respond, rpc,
)

OUTPUT = ROOT / "n8n" / "workflows" / "lead-demo-owner-action.json"
WORKFLOW_NAME = f"{PREFIX} 6. Demo owner action"
WEBHOOK_PATH = "lead-demo-owner"


def config_code(env: dict) -> str:
    settings = {
        "supabase_url": env["SUPABASE_URL"].rstrip("/"),
        "approvals_channel": env["SLACK_APPROVALS_CHANNEL_ID"],
    }
    return ("// Settings for this workflow. Generated by scripts/build_n8n_workflows.py.\n"
            f"return [{{ json: {json.dumps(settings, indent=2)} }}];")


VALIDATE_CODE = """// The site sends the visitor's private thread link and which button they clicked.
const b = $('Owner action').first().json.body || {};
const token = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(b.token || '') ? b.token : null;
return [{ json: { valid: Boolean(token) && typeof b.approved === 'boolean', token, approved: b.approved === true } }];"""


SLACK_UPDATE_CODE = SLACK_BLOCKS_JS + r"""
// The Slack message for this price: swap its buttons for the outcome.
const config = $('Config').first().json;
const r = $('Resolve approval').first().json;
if (!r.changed || !r.slack_ts) return [];
const outcome = r.status === 'approved'
  ? ':white_check_mark: Approved on the demo site by a visitor playing the owner, and sent to their web thread.'
  : ':x: Rejected on the demo site by a visitor playing the owner. Nothing was sent; the lead was handed off.';
const p = { approval_id: r.approval_id, who: whoLine(r.lead), summary: r.lead.summary, reply: r.reply };
return [{ json: { body: { channel: config.approvals_channel, ts: r.slack_ts, text: outcome,
                          blocks: priceApprovalBlocks(p, outcome) } } }];"""


def build_owner_action_workflow(env: dict) -> dict:
    y, row2 = 300, 520
    x = lambda col: col * 230  # noqa: E731
    nodes = [
        node("Owner action", "n8n-nodes-base.webhook", 2, (x(0), y), {
            "httpMethod": "POST", "path": WEBHOOK_PATH, "authentication": "headerAuth",
            "responseMode": "responseNode", "options": {},
        }, webhookId=node_id("owner-action-webhook")),
        code("Config", (x(1), y), config_code(env)),
        code("Validate input", (x(2), y), VALIDATE_CODE),
        if_node("Valid?", (x(3), y), "={{ $json.valid }}", IS_TRUE),
        respond("Reply invalid", (x(4), row2), 400, "={{ { error: 'invalid_request' } }}"),
        rpc("Resolve approval", (x(4), y), "visitor_resolve_approval",
            "={{ JSON.stringify({ p_token: $json.token, p_approved: $json.approved }) }}",
            onError="continueErrorOutput"),
        respond("Reply done", (x(5), y), 200,
                "={{ { changed: $json.changed, status: $json.status || null, error: $json.error || null } }}"),
        respond("Reply failed", (x(5), row2), 502, "={{ { error: 'failed' } }}"),
        code("Plan Slack update", (x(6), y), SLACK_UPDATE_CODE),
        node("Update Slack message", "n8n-nodes-base.httpRequest", 4.2, (x(7), y), {
            "method": "POST",
            "url": "https://slack.com/api/chat.update",
            "authentication": "predefinedCredentialType",
            "nodeCredentialType": "slackApi",
            "sendBody": True,
            "specifyBody": "json",
            "jsonBody": "={{ JSON.stringify($json.body) }}",
            "options": {},
        }, onError="continueRegularOutput"),
    ]
    connections = {
        "Owner action": link("Config"),
        "Config": link("Validate input"),
        "Validate input": link("Valid?"),
        "Valid?": branch(["Resolve approval"], ["Reply invalid"]),
        "Resolve approval": branch(["Reply done"], ["Reply failed"]),
        "Reply done": link("Plan Slack update"),
        "Plan Slack update": link("Update Slack message"),
    }
    return {"name": WORKFLOW_NAME, "nodes": nodes, "connections": connections,
            "settings": {"executionOrder": "v1"}}
