"""Write dashboard/.env.local from the project's .env.

The dashboard only needs a few of the project's settings. This copies exactly
those, so there is one place to change a value. The same names go into the
Vercel project's environment variables.

Usage (from the project root):
    python scripts/sync_dashboard_env.py
"""

from __future__ import annotations

from build_n8n_workflows import ROOT, load_env

KEYS = [
    "SUPABASE_URL",
    "SUPABASE_SERVICE_ROLE_KEY",
    "N8N_BASE_URL",
    "N8N_WEBHOOK_SECRET",
    "IP_HASH_SALT",
    "DEMO_LEADS_PER_IP_PER_DAY",
    "DEMO_MESSAGES_PER_THREAD",
    "DEMO_DAILY_AI_CALL_CAP",
]


def main() -> None:
    env = load_env()
    missing = [k for k in KEYS if not env.get(k)]
    if missing:
        raise SystemExit(f"Missing in .env: {', '.join(missing)}")
    lines = ["# Generated by scripts/sync_dashboard_env.py from ../.env. Don't edit by hand."]
    lines += [f"{k}={env[k]}" for k in KEYS]
    path = ROOT / "dashboard" / ".env.local"
    # Plain LF line endings, so the file pastes cleanly into Vercel.
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {path.relative_to(ROOT)} ({len(KEYS)} settings)")


if __name__ == "__main__":
    main()
